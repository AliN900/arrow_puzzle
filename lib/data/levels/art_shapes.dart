/// ASCII-art silhouettes for art levels.
///
/// Rules for every shape:
///   - All rows are exactly the same length.
///   - Silhouette is centered with a tight bounding box (no empty border).
///   - Minimum 2 cells thick everywhere so arrows have room to snake.
///   - Aspect ratios fit nicely on phone screens.
class ArtShape {
  final String id;
  final String name;
  final List<String> rows;

  const ArtShape({
    required this.id,
    required this.name,
    required this.rows,
  });

  int get width => rows.map((r) => r.length).reduce((a, b) => a > b ? a : b);
  int get height => rows.length;

  Set<String> toMask() {
    final mask = <String>{};
    for (int r = 0; r < rows.length; r++) {
      final row = rows[r];
      for (int c = 0; c < row.length; c++) {
        if (row[c] == 'X') mask.add('$r,$c');
      }
    }
    return mask;
  }
}

